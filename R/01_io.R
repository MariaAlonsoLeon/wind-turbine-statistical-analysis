#' Lee un fichero anual con nombres limpios y tipos explícitos
#'
#' `Log Time` e `Inv Time` se leen como texto (se parsean en 02_cleaning.R);
#' el resto como numérico con punto decimal, según el diccionario. Los valores
#' no numéricos se convierten en NA y quedan registrados en el atributo
#' "parse_problems" (no se pierden silenciosamente).
#'
#' @param path Ruta al CSV original.
#' @param schema Esquema (scada_schema()).
#' @return tibble con columnas limpias + source_file.
load_year_data <- function(path, schema = scada_schema()) {
  header <- read_raw_header(path)
  name_map <- stats::setNames(schema$name, schema$original)
  if (!all(header %in% names(name_map))) {
    stop("Columnas no documentadas en ", basename(path), ": ",
         paste(setdiff(header, names(name_map)), collapse = ", "),
         call. = FALSE)
  }
  clean_names <- unname(name_map[header])
  col_types <- readr::cols(.default = readr::col_double(),
                           log_time_raw = readr::col_character(),
                           inv_time_raw = readr::col_character())
  data <- readr::read_delim(
    path, delim = ";", skip = 1, col_names = clean_names,
    col_types = col_types, locale = readr::locale(decimal_mark = "."),
    trim_ws = TRUE, na = c("", "NA"), progress = FALSE
  )
  problems <- readr::problems(data)
  data <- dplyr::mutate(data, source_file = basename(path), .before = 1)
  attr(data, "parse_problems") <- dplyr::mutate(problems,
                                                file = basename(path))
  data
}

#' Lee y combina todos los años
#'
#' Comprueba antes la compatibilidad del esquema y conserva los problemas de
#' parseo de cada fichero en el atributo "parse_problems".
#'
#' @param files Salida de list_raw_files().
#' @return tibble combinado (filas en el orden original de los ficheros).
load_all_years <- function(files = list_raw_files()) {
  assert_schema_compatible(validate_schema(files))
  pieces <- lapply(files$path, load_year_data)
  problems <- dplyr::bind_rows(lapply(pieces, attr, "parse_problems"))
  data <- dplyr::bind_rows(pieces)
  data <- dplyr::left_join(data,
                           dplyr::select(files, source_file = file,
                                         file_year = year),
                           by = "source_file")
  attr(data, "parse_problems") <- problems
  data
}
