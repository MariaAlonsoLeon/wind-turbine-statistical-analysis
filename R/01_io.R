#' Detecta los ficheros anuales en data/raw
#'
#' @param raw_dir Directorio con los CSV originales.
#' @param pattern Expresión regular con el año como primer grupo.
#' @return tibble con file, path, year (del nombre) y size_mb.
list_raw_files <- function(raw_dir = project_path("raw_dir"),
                           pattern = load_config()$raw_format$file_pattern) {
  files <- sort(list.files(raw_dir, pattern = pattern, full.names = TRUE))
  if (length(files) == 0) {
    stop("No hay ficheros 'data_swt_iee_usp_YYYY.csv' en ", raw_dir,
         ".\nConsulta data/README.md para descargarlos.", call. = FALSE)
  }
  tibble::tibble(
    file = basename(files),
    path = files,
    year = as.integer(sub(pattern, "\\1", basename(files))),
    size_mb = round(file.size(files) / 1024^2, 2)
  )
}

#' Manifiesto de los ficheros originales (tamaño y huella MD5)
#'
#' Permite comprobar que data/raw no se modifica accidentalmente.
raw_manifest <- function(files) {
  dplyr::mutate(files[c("file", "year", "size_mb")],
                md5 = unname(tools::md5sum(files$path)))
}

#' Cabecera de un fichero con espacios exteriores eliminados
#'
#' Nota: en 2017 la columna T1 aparece como " T1" (con espacio inicial).
read_raw_header <- function(path, delim = ";") {
  header <- readLines(path, n = 1, warn = FALSE)
  trimws(strsplit(header, delim, fixed = TRUE)[[1]])
}

# -----------------------------------------------------------------------------
# Validación del esquema
# -----------------------------------------------------------------------------

#' Compara la cabecera de cada fichero con el esquema documentado
#'
#' @return tibble (una fila por fichero) con nº de columnas, columnas que
#'   faltan, columnas no documentadas, orden y compatibilidad.
validate_schema <- function(files, schema = scada_schema()) {
  rows <- lapply(seq_len(nrow(files)), function(i) {
    header <- read_raw_header(files$path[i])
    raw_header <- strsplit(readLines(files$path[i], n = 1, warn = FALSE),
                           ";", fixed = TRUE)[[1]]
    missing <- setdiff(schema$original, header)
    extra <- setdiff(header, schema$original)
    tibble::tibble(
      file = files$file[i],
      n_columns = length(header),
      missing_columns = paste(missing, collapse = ", "),
      extra_columns = paste(extra, collapse = ", "),
      same_order = identical(header, schema$original),
      names_with_spaces = paste(raw_header[raw_header != trimws(raw_header)],
                                collapse = ", "),
      compatible = length(missing) == 0 && length(extra) == 0
    )
  })
  dplyr::bind_rows(rows)
}

#' Detiene la ejecución si algún fichero no es compatible con el esquema
assert_schema_compatible <- function(schema_check) {
  bad <- schema_check$file[!schema_check$compatible]
  if (length(bad) > 0) {
    stop("Estructura de columnas incompatible en: ",
         paste(bad, collapse = ", "),
         ". Revisa la salida de validate_schema().", call. = FALSE)
  }
  invisible(TRUE)
}

